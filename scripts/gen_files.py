def fmt_ts_array(name, arr):
    lines = [f"export const {name} = new Float64Array(["]
    for i in range(0, len(arr), 5):
        chunk = arr[i:i+5]
        line = "  " + ",".join(f"{v:.12f}" for v in chunk)
        if i + 5 < len(arr):
            line += ","
        lines.append(line)
    lines.append("]);")
    return "\n".join(lines)

